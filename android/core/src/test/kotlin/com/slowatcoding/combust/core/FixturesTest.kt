import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/** Replays the golden fixtures generated by the web code (`spec/fixtures`). */
class FixturesTest {
    private fun fixture(name: String): JsonElement {
        val dir = System.getProperty("combust.fixtures") ?: error("combust.fixtures not set")
        return Json.parseToJsonElement(File(dir, "$name.json").readText())
    }

    private fun JsonElement.str(key: String) = jsonObject[key]!!.jsonPrimitive.content
    private fun JsonElement.strOrNull(key: String) = jsonObject[key]?.takeIf { it !is JsonNull }?.jsonPrimitive?.content
    private fun JsonElement.dblOrNull(key: String): Double? =
        jsonObject[key]?.takeIf { it !is JsonNull }?.jsonPrimitive?.double

    private fun assertNear(msg: String, expected: Double?, actual: Double?) {
        if (expected == null) assertNull(msg, actual)
        else {
            requireNotNull(actual) { "$msg expected $expected but was null" }
            assertEquals(msg, expected, actual, 1e-9)
        }
    }

    private fun entryOf(e: JsonElement) = FuelEntry(
        id = e.str("id"),
        vehicleId = e.str("vehicleId"),
        date = e.str("date"),
        odometerReading = e.jsonObject["odometerReading"]!!.jsonPrimitive.double,
        fuelStation = e.str("fuelStation"),
        amountPaid = e.jsonObject["amountPaid"]!!.jsonPrimitive.double,
        litresFilled = e.jsonObject["litresFilled"]!!.jsonPrimitive.double,
        isFullTank = e.jsonObject["isFullTank"]!!.jsonPrimitive.boolean,
        missedPrevious = e.jsonObject["missedPrevious"]!!.jsonPrimitive.boolean,
    )

    @Test
    fun deriveAndStats() {
        val cases = fixture("derive").jsonArray
        assert(cases.size > 40)
        for (case in cases) {
            val name = case.str("name")
            val entries = case.jsonObject["entries"]!!.jsonArray.map(::entryOf)
            val derived = deriveEntries(entries)

            val expected = case.jsonObject["derived"]!!.jsonArray
            assertEquals("$name: derived size", expected.size, derived.size)
            expected.forEachIndexed { i, exp ->
                val got = derived[i]
                val at = "$name[${exp.str("id")}]"
                assertEquals("$at id", exp.str("id"), got.id)
                assertEquals("$at isPending", exp.jsonObject["isPending"]!!.jsonPrimitive.boolean, got.isPending)
                assertEquals("$at isPartial", exp.jsonObject["isPartial"]!!.jsonPrimitive.boolean, got.isPartial)
                assertEquals("$at hasGap", exp.jsonObject["hasGap"]!!.jsonPrimitive.boolean, got.hasGap)
                assertEquals(
                    "$at isOdometerRegression",
                    exp.jsonObject["isOdometerRegression"]!!.jsonPrimitive.boolean,
                    got.isOdometerRegression,
                )
                assertNear("$at distanceCovered", exp.dblOrNull("distanceCovered"), got.distanceCovered)
                assertNear("$at mileage", exp.dblOrNull("mileage"), got.mileage)
                assertNear("$at costPerLitre", exp.dblOrNull("costPerLitre"), got.costPerLitre)
            }

            val overall = computeOverallStats(derived)
            val eo = case.jsonObject["overall"]!!
            assertNear("$name averageMileage", eo.dblOrNull("averageMileage"), overall.averageMileage)
            assertNear("$name totalLitres", eo.dblOrNull("totalLitresFilled"), overall.totalLitresFilled)
            assertNear("$name totalAmount", eo.dblOrNull("totalAmountSpent"), overall.totalAmountSpent)
            assertNear("$name avgCost", eo.dblOrNull("averageCostPerLitre"), overall.averageCostPerLitre)
            assertNear("$name totalDistance", eo.dblOrNull("totalDistanceCovered"), overall.totalDistanceCovered)
            assertEquals("$name entryCount", eo.jsonObject["entryCount"]!!.jsonPrimitive.int, overall.entryCount)
            assertEquals("$name best", eo.strOrNull("bestMileageEntryId"), overall.bestMileageEntry?.id)
            assertEquals("$name worst", eo.strOrNull("worstMileageEntryId"), overall.worstMileageEntry?.id)

            val stations = computeStationStats(derived)
            val es = case.jsonObject["stations"]!!.jsonArray
            assertEquals("$name stations size", es.size, stations.size)
            es.forEachIndexed { i, exp ->
                assertEquals("$name station", exp.str("station"), stations[i].station)
                assertEquals("$name fillCount", exp.jsonObject["fillCount"]!!.jsonPrimitive.int, stations[i].fillCount)
                assertNear("$name st avg", exp.dblOrNull("averageMileage"), stations[i].averageMileage)
                assertNear("$name st cost", exp.dblOrNull("averageCostPerLitre"), stations[i].averageCostPerLitre)
                assertNear("$name st spent", exp.dblOrNull("totalAmountSpent"), stations[i].totalAmountSpent)
            }

            val trend = computeMileageTrend(derived)
            val et = case.jsonObject["trend"]
            if (et == null || et is JsonNull) assertNull("$name trend", trend)
            else {
                requireNotNull(trend) { "$name trend expected" }
                assertNear("$name trend ratio", et.dblOrNull("ratio"), trend.ratio)
                assertEquals("$name trend dir", et.str("direction"), trend.direction.name.lowercase())
            }
        }
    }

    @Test
    fun sectorsPipsAndStationCodes() {
        val root = fixture("sector")
        val scenarios = fixture("derive").jsonArray.associateBy { it.str("name") }
        for (case in root.jsonObject["cases"]!!.jsonArray) {
            val name = case.str("name")
            val entries = scenarios[name]!!.jsonObject["entries"]!!.jsonArray.map(::entryOf)
            val derived = deriveEntries(entries)
            val overall = computeOverallStats(derived)
            val bestId = overall.bestMileageEntry?.id
            assertEquals("$name bestId", case.strOrNull("bestId"), bestId)
            case.jsonObject["rows"]!!.jsonArray.forEachIndexed { i, row ->
                val sector = sectorOf(derived[i], overall.averageMileage, bestId)
                assertEquals("$name[$i] sector", row.str("sector"), sector.name.lowercase())
                val pips = row.jsonObject["pips"]?.takeIf { it !is JsonNull }?.jsonPrimitive?.int
                val m = derived[i].mileage
                assertEquals("$name[$i] pips", pips, m?.let { pipsOf(it, overall.averageMileage, sector) })
            }
        }
        for (c in root.jsonObject["stationCodes"]!!.jsonArray) {
            assertEquals("code of '${c.str("name")}'", c.str("code"), stationCode(c.str("name")))
        }
    }

    @Test
    fun odometerWarnings() {
        val root = fixture("odometer-warning")
        val entries = root.jsonObject["entries"]!!.jsonArray.map(::entryOf)
        for (c in root.jsonObject["cases"]!!.jsonArray) {
            val odo = c.jsonObject["odometer"]!!.jsonPrimitive.double
            val exclude = c.strOrNull("excludeId")
            assertEquals(
                "odometer $odo exclude $exclude",
                c.strOrNull("warning"),
                getOdometerWarning(entries, odo, exclude, Locale.US),
            )
        }
    }

    @Test
    fun groupByMonthLabels() {
        val root = fixture("group-by-month")
        val rows = root.jsonObject["rows"]!!.jsonArray.map { it.str("id") to it.str("date") }
        val groups = groupByMonth(rows) { it.second }
        val expected = root.jsonObject["groups"]!!.jsonArray
        assertEquals(expected.size, groups.size)
        expected.forEachIndexed { i, g ->
            assertEquals(g.str("label"), groups[i].label)
            assertEquals(g.jsonObject["items"]!!.jsonArray.map { it.str("id") }, groups[i].items.map { it.first })
        }
    }

    @Test
    fun csvParsing() {
        for (case in fixture("csv").jsonArray) {
            val text = case.str("text")
            val result = parseFuelEntriesCsv(text)
            val exp = case.jsonObject["result"]!!
            val expRows = exp.jsonObject["rows"]!!.jsonArray
            assertEquals("rows for ${text.take(40)}", expRows.size, result.rows.size)
            expRows.forEachIndexed { i, r ->
                val got = result.rows[i]
                assertEquals(r.str("date"), got.date)
                assertEquals(r.str("fuelStation"), got.fuelStation)
                assertEquals(r.jsonObject["amountPaid"]!!.jsonPrimitive.double, got.amountPaid, 1e-9)
                assertEquals(r.jsonObject["odometerReading"]!!.jsonPrimitive.double, got.odometerReading, 1e-9)
                assertEquals(r.jsonObject["litresFilled"]!!.jsonPrimitive.double, got.litresFilled, 1e-9)
                assertEquals(r.jsonObject["isFullTank"]!!.jsonPrimitive.boolean, got.isFullTank)
                assertEquals(r.jsonObject["missedPrevious"]!!.jsonPrimitive.boolean, got.missedPrevious)
            }
            val expErrors = exp.jsonObject["errors"]!!.jsonArray.map {
                it.jsonObject["line"]!!.jsonPrimitive.int to it.str("reason")
            }
            assertEquals(expErrors, result.errors.map { it.line to it.reason })
        }
    }
}
